import Foundation

/// **这一段录音里到底有没有人说话** —— 判据挂在**音频本身**上。
///
/// 🚨🚨 **为什么要有这个文件**：键盘在「后端回了但一个字都没有」时，
///    要决定给他哪句话 ——
///      · 真没说话（口袋里误触、静音）→ 「再说一次」
///      · 说了但没出结果          → 「刚才那段还在，点一下重发」
///    **给反了都很难受**：让他重发一段静音，只会拿到同样的结果，
///    把他关进循环；让他把说过的话重说一遍，正是他 2026-09-06 01:50
///    骂的那件事（「都已经录进去了，干嘛让我再说一次」）。
///
/// 🚨🚨 **上一版我把判据挂在 `zh` 上**（后端识别出的中文是不是空的）。
///    那是**模型返回的东西**，而 1.1 实测过：同一段静音，模型三次给出三种说法
///    （空串 / 「你所给音频无有效说话内容。」/ 「啊?」）。
///    **追模型的措辞永远追不上** —— 判据必须挂在**输入**上，不是挂在**输出**上。
///
/// 🚨🚨🚨 **阈值不许我拍脑袋。**
///    `Voice` 给的电平 `lv` 是经过 `sqrt` 曲线 + ×1.9 压过的 0…1 值，
///    「多少算说话」**没有先验答案**。所以这里**不用绝对阈值**，用
///    **峰值 ÷ 底噪** —— 同一段录音里自带参照，换设备、换环境都不用重标。
///
///    ⚠️ 下面那个 `minRatio = 3.0` 仍然是**待标定**的：它是从
///    「说话通常比本底大一个量级、而纯底噪的起伏在 2 倍以内」推来的，
///    **还没有拿 Kevin 真机上的一条静音样本和一条说话样本量过**。
///    → `Voice` 每次录完都会把 `peak/floor/ratio` 写进诊断日志，
///      拿到一条真静音 + 一条真说话之后**回来把这个数改成量出来的**。
///      在那之前，本判据**偏向保守**：拿不准时按「他说了话」处理
///      （宁可让他多点一下重发，也不要让他把说过的话重说一遍）。
enum SpeechPresence {

    /// 一段录音的电平统计。`Voice` 边录边喂，录完取出来。
    struct Stats: Equatable {
        /// 整段的最大电平（0…1）
        var peak: Float = 0
        /// 本底：所有帧里**最小的那一档**（安静时的地板）
        var floor: Float = 1
        /// 收到多少帧 —— 太少的话统计不作数
        var frames: Int = 0

        mutating func feed(_ lv: Float) {
            frames += 1
            if lv > peak { peak = lv }
            if lv < floor { floor = lv }
        }

        /// 峰值是本底的多少倍。本底为 0 时按一个极小值兜底，避免除零。
        var ratio: Float {
            let f = max(floor, 0.0001)
            return peak / f
        }

        /// 给诊断日志用的一行，**真实数字**，用来事后标定阈值。
        var debugLine: String {
            String(format: "peak=%.4f floor=%.4f ratio=%.1f frames=%d",
                   peak, floor, ratio, frames)
        }
    }

    /// 🚨 **待标定**：见文件顶部。改这个数之前先拿真样本量一遍。
    static let minRatio: Float = 3.0
    /// 帧数太少（不到 ~0.3 秒）时统计没有意义。
    static let minFrames = 3

    /// 这一段里有没有人说话。
    ///
    /// 🚨 **拿不准一律回 `true`**（当作说过话）。两种错的代价不对称：
    ///    · 误判成"没说话" → 让他把说过的话**重说一遍** ← 他专门骂过这件事
    ///    · 误判成"说了话" → 让他多点一下重发，最多白跑一次
    ///    所以判据往"他说了"那边偏。
    static func spoke(_ s: Stats) -> Bool {
        guard s.frames >= minFrames else { return true }   // 样本不够，不下结论
        guard s.peak > 0 else { return false }             // 全 0 = 麦克风没进声音
        return s.ratio >= minRatio
    }
}
