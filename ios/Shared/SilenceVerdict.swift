import Foundation

/// 「这一段到底有没有收到声音」—— **纯判据，从录音路径抽出来只为能验。**
///
/// 🚨 Kevin 2026-09-06 亲口，而且说「不止一次出现」：
///    「说了一堆话，界面显示正在录音，点结束后提示第一段未转出无内容」
///    「说了这么多话却被告知没转出，**也没有重新上传处理的按钮**」
///
/// 🚨🚨 判据是**零采样点占比**，不是峰值。
///    峰值 2026-08-31 被正负样本当场判死：安静环境读 1334、
///    **放着声音反而读 575** —— 它量的根本不是"房间里有没有声音"。
///    而这道闸一直在用它，`zeroPct` 只活在探针里。
///    **判据验过了，却没装到出事的那条路上。**
enum SilenceVerdict {

    /// 判成「麦克风真的没收到声音」的门槛。
    ///
    /// 🚨 用 `>= 98` 不用 `== 100`：WAV 头之后偶有一两个非零采样点，
    ///    卡死 100 会让这道闸**永远不成立** —— 假检查的经典形态
    ///    （写了个判断，但没有任何真实输入能让它为真）。
    static let deadZeroPct = 98

    /// 麦克风是不是真的什么都没收到。`zeroPct` 为 -1（数据太短）时**当作"有声音"**。
    ///
    /// 🚨 拿不准要偏向「他说了话」：两种错的代价不对称 ——
    ///    误判成"没声音"会把他说的一大段扔掉（他骂的就是这个）；
    ///    误判成"有声音"最多让他多点一次重发。
    static func micGotNothing(zeroPct: Int) -> Bool {
        guard zeroPct >= 0 else { return false }
        return zeroPct >= deadZeroPct
    }

    /// 后端说要重说时，**这段音频还留不留**。
    ///
    /// 🚨 留住 ≠ 自动重传：按钮由他点。原来那条"避免无限重传"的注释
    ///    担心的是自动重传，而我们从来没做过自动重传 ——
    ///    **它拿一个不存在的风险，换掉了他真说过的那段话。**
    static func keepAudioForRetry(needsRespeak: Bool, zeroPct: Int) -> Bool {
        guard needsRespeak else { return true }      // 别的失败本来就留
        return !micGotNothing(zeroPct: zeroPct)
    }
}
