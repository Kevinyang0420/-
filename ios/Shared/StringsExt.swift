import Foundation

/// **`L` 里生成器表达不了的那部分。**
///
/// 🚨🚨 2026-09-05 事故：2.1 跑了一次 `gen_ios_strings.py`，
///    它**按 `i18n_map.py` 整体重写 `Strings.swift`**，把 25 个
///    「只存在于生成物里、从没进过 map」的成员**全部冲掉**，iOS 直接编不过。
///
/// 教训分两层：
/// ① **写进生成物的东西，下一次重跑生成必然被冲掉。** 普通常量的正解是
///    补进 `i18n_map.py`（唯一配置点），不是补回 `Strings.swift`。
/// ② **但有些东西 `i18n_map` 表达不了** —— 它的模板只会吐
///    `static var xxx: String { s(zh, en, hant) }`。带参数的、
///    带逻辑的，硬塞进去就是把生成器改复杂，下次还得再改。
///    → 这类放**这个文件**：生成器不认识它，也就不会碰它。
///
/// 🚨 判据：**这个文件里的每一条都必须是"生成器写不出来的"**。
///    普通常量跑到这里来，等于又开了一个"只存在于代码里的配置点"，
///    下次有人补 `i18n_map` 时会漏掉它 —— 那正是今天出事的形状。
extension L {

    // MARK: - 带参数的键面文案

    /// 空格键 / 完成键的键面。
    ///
    /// 🚨🚨 **只看 `english`（打字档），不看界面语言。**
    ///    Kevin 2026-09-04 定的：**键面跟打字档走，不跟界面语言走** ——
    ///    中文界面下切到英文打字档，键面就该是 `space`/`Done`。
    ///
    /// 🚨 我 2026-09-05 重建这两个函数时**两处都写错了**：
    ///    ① 值编成了 `换行`/`return`（原文是 `完成`/`Done`）；
    ///    ② 接线接成了跟界面语言走（`isEn`/`isHant`）——**正好违反上面那条规矩**。
    ///    原文是 2.1 从会话记录里捞回来的字面内容，不是谁的记忆。
    ///    → **文件没了就去找原文，别凭用法反推**：反推出来的东西看着合理，
    ///      但它把"我以为的规则"写进了代码，而真规则在别处。
    ///
    /// 🚨 原注释里那句留着：**「当年漏了 —— 同一条规矩没按每个出口落地」**。
    static func kb_space_face(_ english: Bool) -> String {
        english ? "space" : "空格"
    }

    static func kb_done_face(_ english: Bool) -> String {
        english ? "Done" : "完成"
    }

    // MARK: - 占位符填充

    /// 把文案里的 `%@` 换成给定的值。
    ///
    /// 🚨 **不用 `String(format:)`** —— 文案是可翻译的，
    ///    英文那版少一个 `%@` 或多一个就会崩，而崩在用户手上。
    ///    这里做成纯字符串替换：多了不崩，少了也不崩。
    static func fill(_ tpl: String, _ a: String) -> String {
        tpl.replacingOccurrences(of: "%@", with: a)
    }
}
