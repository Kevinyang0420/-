import UIKit

/// **目标语言选择器的共用件** —— 最近用过置顶 + 全量滚动（Kevin 2026-09-05 定的方案乙）。
///
/// 🚨 他的原话：「你选择器不要一下子展示那么多嘛，加个下拉，就可以支持我滑动去选了嘛，
///    所以 32 项又怎么样嘛」。语言表要从 9 门扩到 23+ 门。
///
/// 🚨 为什么做成共用件：目标语言的选择器**有三处**（随手 / 面对面 / 键盘），
///    清单本身已经收在 `Backend.langs` 一处了，但**"怎么排、怎么显示"各写各的** ——
///    9 门时看不出来，23 门时三处会各坏各的。
enum LangRecents {
    private static let key = "vime.lang.recent"
    /// 使用次数。**跟 `key` 那份最近顺序是两回事，别合并。**
    private static let countKey = "vime.lang.count"

    /// 用过的语言码，**最近用的在前**（只用于同次数时的平局判定）。
    ///
    /// 🚨🚨 **不再截断到 3 条。** Kevin 2026-09-06 01:40：
    ///    「最近的语言要支持左右滑动，**永远前面放最常用的前三个**，
    ///      **用过的都可以左右滑取出来**」
    ///    —— 截断到 3 就没有"都可以滑出来"这回事了。
    ///    前三个由**排序**保证，不是由截断保证。**这两件事以前被混成了一件。**
    static var codes: [String] {
        (KbBridge.prefs.array(forKey: key) as? [String]) ?? []
    }

    /// 每门语言用过多少次。
    ///
    /// 🚨🚨 **老用户升级时要迁移**（2.1 2026-09-06；PC 端已这么做）。
    ///    计数是 09-06 才加的，升级前的用户只有一份「最近用过」的顺序、**没有次数**。
    ///    不迁移的话所有老语言都是 0 次 —— 他之后随手用一门新语言就立刻 1 分
    ///    **冲到最前，把天天用的那门顶下去**，看起来就是"排序乱了"。
    ///
    /// 🚨 迁移只做一次，判据是「有最近记录但一条计数都没有」。
    ///    每门**记 1 次**（不是按位置给 3/2/1）—— 位置信息已经在 `codes` 里，
    ///    平局时由它决定顺序；再按位置编一套次数等于**同一件事两个来源**。
    static var counts: [String: Int] {
        if let d = KbBridge.prefs.dictionary(forKey: countKey) as? [String: Int],
           !d.isEmpty {
            return d
        }
        // 🚨 规则本体在 `LangRank.seedCounts`（纯函数），这里只负责落盘。
        guard let seeded = LangRank.seedCounts(used: codes, existing: [:]) else {
            return [:]
        }
        KbBridge.prefs.set(seeded, forKey: countKey)
        return seeded
    }

    /// 记一次使用。🚨 **唯一写入口**：三个选择器都调它，
    ///    各写一份的话"最近用过"在三个界面会给出三种顺序。
    static func use(_ code: String) {
        guard !code.isEmpty else { return }
        var v = codes.filter { $0 != code }
        v.insert(code, at: 0)
        KbBridge.prefs.set(v, forKey: key)
        var c = counts
        c[code] = (c[code] ?? 0) + 1
        KbBridge.prefs.set(c, forKey: countKey)
    }

    /// 排好序的两段：(最近用过, 全部语言)。
    ///
    /// 🚨 「最近用过」**按真实使用记录变**，不是写死三门 —— 这是 2.1 的判据②。
    /// 🚨 一条记录都没有时返回空的第一段，界面**不画那个小标题**，
    ///    不要显示一个空分区。
    /// 分成「最近用过」和「全部语言（含最近用过）」。
    ///
    /// 🚨🚨 **第二个返回值故意包含 recent，这是方案丙定的**
    ///    （Kevin 2026-09-05 13:0x 拍板：「语言列表选丙」）：
    ///    **「全部语言」保持完整不删** —— 所有语言都在，不因使用历史变化。
    ///
    /// 🚨 那为什么他早上会看到「中文」两次？**问题从来不在数据，在渲染**：
    ///    键盘那屏把两段 **拼平** 成一个列表（`recent + all`），
    ///    两段长得一模一样，重复就被读成 bug。
    ///    丙的解法是**把「最近用过」做成横滑 chips**（描边不填充、更扁），
    ///    跟下面的列表行**明显不同类** —— 就像浏览器的"常用站点"和"书签列表"，
    ///    同一个站出现两次没人觉得是错。
    ///
    /// 🚨🚨 **名字改了，因为旧名字骗过人**：原来叫 `rest`（其余）而实际返回全量，
    ///    2026-09-05 有两个人（我和 0）先后照着名字推理、各错一次。
    ///    我一度还"修"成真的去重 —— **那是改对了名字理解、改错了产品意图**。
    ///    现在名字如实：`allIncludingRecent`。
    ///    **只改现象不改名字，下一个人还会踩同一脚。**
    /// 🚨🚨 **「最常用」≠「最近用」。** Kevin 2026-09-06 01:40 说的是
    ///    「永远前面放**最常用**的前三个」—— 那是**用过的次数最多**，
    ///    不是最近点过的。两者在他的用法下会给出完全不同的顺序：
    ///    偶尔试一次的语言会把天天用的那门顶下去。
    ///
    /// 🚨 排序 = **次数降序，平局才看最近时间**。
    ///    只按次数的话，两门都用过 1 次时顺序会随字典遍历乱跳。
    /// 🚨 规则本体在 `LangRank.rank`（纯函数、无依赖），这里只负责把存储喂给它。
    ///    分开是为了让判据能在测试包里跑 —— UI 测试是独立进程，
    ///    `@testable import` 链接不到 App 符号，读不了 App Group。
    static func ranked(_ all: [String]) -> [String] {
        return LangRank.rank(used: codes, counts: counts, all: all)
    }

    static func sections(all: [String])
        -> (recent: [String], allIncludingRecent: [String]) {
        return (ranked(all), all)
    }

}

