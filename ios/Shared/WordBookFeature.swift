import Foundation

/// 单词本在这一端**上线了没有**。
///
/// 产品经理 2026-08-28 定的规矩：
///   · 功能**未**上线 → 点「单词本」**不弹登录门**，直接说「即将上线」，
///     **一个字都不提登录**。理由：挂一扇门、门后是空的，登录之后还是用不了，
///     那就是"骗一次注册"。**门是为了兑现某个东西才存在的，兑现不了就不该有门。**
///   · 功能**已**上线 → 门必须挂上，且文案跟安卓那句一模一样。
///
/// 🚨🚨 **"上线了没有"必须由一个可检测的事实决定，不许靠人记得去改。**
///    这里的事实是：**iOS 有没有办法把词收进单词本**。
///    现在没有 —— 三个视图做完了，但：
///      · 键盘的「收藏」入口是安卓独有的
///      · iOS 键盘是**扩展进程**，要先配 App Group 才写得到主 App 读得到的地方
///    所以 iOS 的单词本目前是一个**永远空着的阅读器**。
///    视图存在 ≠ 功能可用，**别拿"页面做出来了"当上线**。
///
/// 🚨 改这个常量**必须同时**让 `gate_wordbook_copy.py` 通过 ——
///    那道闸门双向都有坏样本：
///      · 标 `false` 却在键盘里能收词 → 红（漏改文案，会永远停在"即将上线"）
///      · 标 `true` 却没有任何收词入口 → 红（假承诺，登录后用不了）
enum WordBookFeature {

    /// iOS 单词本能不能真用起来。
    ///
    /// 判据 = **键盘扩展里有没有"收进单词本"的调用**（`WordBook.add`）。
    /// 闸门会拿源码里的事实来核这个常量，不核就不许改。
    /// 🚨 2026-08-28 改成 true：**随手翻译的结果上加了「收藏」**，
    ///    iOS 终于有办法把词收进单词本了（在主 App 进程里，不用 App Group）。
    ///    键盘里也能收要等 App Group —— 那是"更多入口"，不是"能不能用"。
    ///    改这一行之后 `gate_wordbook_copy.py` 会**要求把登录门挂回来**。
    static let isLive = true
}
